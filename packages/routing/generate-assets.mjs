// Explicit maintenance command: node packages/routing/generate-assets.mjs
// Fetches pinned public inputs into memory; never saves raw source JSON or a cache.
import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { isIP } from 'node:net';

const commit = '620722145f883fc5ef450e9a909011c0528c1424';
const base = `https://raw.githubusercontent.com/MetaCubeX/meta-rules-dat/${commit}`;
export const sources = [
  { name: 'domestic-domain', url: `${base}/geo/geosite/geolocation-cn.json`, sha256: '3a53a9eec906fe038dc87f58cb71f96415a1a27a0881b6ecef6f4dba7de02128' },
  { name: 'domestic-ip', url: `${base}/geo/geoip/cn.json`, sha256: '5eb3e8cf06ba15265bdbabad7a99d5f63841662fa75c7c0293ca100fae914e89' },
  { name: 'LICENSE', url: 'https://raw.githubusercontent.com/MetaCubeX/meta-rules-dat/4178770badecb1b349fbcd62c737e0d7a2079729/LICENSE', sha256: '3972dc9744f6499f0f9b2dbf76696f2ae7ad8af9b23dde66d6af86c9dfb36986' },
];

const inputs = await Promise.all(sources.map(async (source) => {
  const response = await fetch(source.url);
  if (!response.ok) throw new Error(`Source request failed: ${source.name}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (createHash('sha256').update(bytes).digest('hex') !== source.sha256) throw new Error(`Source hash mismatch: ${source.name}`);
  return bytes.toString('utf8');
}));

function sourceRules(text, allowed) {
  const source = JSON.parse(text);
  if (source.version !== 2 || Object.keys(source).sort().join(',') !== 'rules,version' || !Array.isArray(source.rules)) throw new Error('Unsupported source schema');
  const output = [];
  for (const rule of source.rules) {
    if (!rule || Object.keys(rule).some((key) => !allowed.includes(key))) throw new Error('Unsupported source rule');
    for (const [key, values] of Object.entries(rule)) {
      if (!Array.isArray(values) || values.some((value) => typeof value !== 'string' || !value || /[,\r\n]/.test(value))) throw new Error('Unsupported rule value');
      for (const value of values) {
        // Leading-dot suffixes have different semantics and must never be widened.
        if (key === 'domain_suffix' && value.startsWith('.')) throw new Error('Unsupported suffix semantics');
        if (key === 'ip_cidr') {
          const [address, prefix, extra] = value.split('/');
          const family = isIP(address);
          if (!family || extra !== undefined || !/^\d+$/.test(prefix) || +prefix > (family === 4 ? 32 : 128)) throw new Error('Invalid CIDR');
          if (family !== 4) continue; // Consistent with IPv4-only deployment.
        }
        output.push(`${{ domain: 'DOMAIN', domain_suffix: 'DOMAIN-SUFFIX', domain_regex: 'DOMAIN-REGEX', ip_cidr: 'IP-CIDR' }[key]},${value}`);
      }
    }
  }
  return output;
}
const domains = sourceRules(inputs[0], ['domain', 'domain_suffix', 'domain_regex']);
const ips = sourceRules(inputs[1], ['ip_cidr']);
if (domains.length !== 5390 || ips.length !== 6525) throw new Error('Pinned rule count changed');
const header = '// Generated by generate-assets.mjs from SHA-256-verified pinned inputs.\n// GPL-3.0-only; see LICENSE.domestic and sources.lock.json.\n';
await writeFile(new URL('./domestic-data.ts', import.meta.url), `${header}export const domesticDomainRules: readonly string[] = ${JSON.stringify(domains, null, 2)};\nexport const domesticIpRules: readonly string[] = ${JSON.stringify(ips, null, 2)};\n`);
await writeFile(new URL('./LICENSE.domestic', import.meta.url), inputs[2]);
await writeFile(new URL('./sources.lock.json', import.meta.url), `${JSON.stringify({ schema: 1, reviewedOn: '2026-10-23', repository: 'https://github.com/MetaCubeX/meta-rules-dat', commit, license: 'GPL-3.0-only', domainRules: domains.length, ipv4Rules: ips.length, sources }, null, 2)}\n`);
