test('stable device-only BPF inventory is accepted; source failures and changing inventory remain unverified', async () => {
  const f = fixture(); f.value.bpf.devicePrograms = 17;
  assert.equal((await observeNetworkHostFixture(deployment, options, f.reader)).verified, true);
  let reads = 0; const bpf = f.reader.bpf;
  f.reader.bpf = async () => { if (++reads === 2) f.value.bpf.inventorySha256 = 'e'.repeat(64); return bpf(); };
  assert.equal((await observeNetworkHostFixture(deployment, options, f.reader)).verified, false);
  for (const settled of [true, false]) {
    const f = fixture(); f.reader.bpf = async () => { throw new NetworkCommandError('NETWORK_COMMAND_FAILED', settled); };
    const result = await observeNetworkHostFixture(deployment, options, f.reader);
    assert.equal(result.verified, false); assert.equal(result.commandsSettled, settled);
  }
});

test('legacy save permits only complete empty builtin ACCEPT tables and never hides mixed rules or bad output', async () => {
  for (const raw of [
    '*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT DROP [0:0]\nCOMMIT\n',
    '*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\n:FOREIGN - [0:0]\nCOMMIT\n',
    '*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\n-A OUTPUT -j ACCEPT\nCOMMIT\n',
    '*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n', '*filter\n', 'garbage', '# only comments\n',
  ]) await rejected(f => { f.value.legacy4 = raw; });
  await rejected(f => { f.value.legacy6 = f.value.legacy4.replace(':OUTPUT ACCEPT', ':OUTPUT DROP'); });
  const f = fixture(); f.value.legacy4 += '*raw\n:PREROUTING ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\nCOMMIT\n';
  assert.equal((await observeNetworkHostFixture(deployment, options, f.reader)).verified, true);
});

test('unstable or malformed observations and unknown read-command failure never become a settled positive', async () => {
  await rejected(f => { let reads = 0; const command = f.reader.command; f.reader.command = async (tool, args) => {
    if (tool === 'ip' && args.includes('link') && ++reads === 2) f.value.links[1].ifindex = 9;
    return command(tool, args);
  }; });
  await rejected(f => { f.reader.bpf = async () => '{"schemaVersion":1,"devicePrograms":0,"inventorySha256":"' + 'd'.repeat(64) + '","devicePrograms":1}'; });
  for (const kind of ['unsettled', 'unknown', 'settled'] as const) {
    const result = await rejected(f => { f.reader.command = async () => {
      if (kind === 'unknown') throw new Error('raw stderr with private data');
      throw new NetworkCommandError('NETWORK_COMMAND_FAILED', kind === 'settled');
    }; });
    assert.equal(result.commandsSettled, kind === 'settled');
  }
  const f = fixture(); let now = 1000; f.reader.now = () => now += 1000;
  assert.equal((await observeNetworkHostFixture(deployment, options, f.reader)).verified, false);
});

test('production never accepts a fixture reader or invalid tool path, even when input is otherwise valid', async () => {
  if (process.platform !== 'linux' || process.geteuid?.() !== 0) {
    const result = await observeNetworkHost(deployment, options);
    assert.equal(result.scope, 'production'); assert.equal(result.verified, false);
  }
  const f = fixture();
  const result = await observeNetworkHostFixture(deployment, { ...options, tcBinary: '/tmp/tc' }, f.reader);
  assert.equal(result.verified, false); assert.deepEqual(f.commands, []);
  let invoked = false;
  const hostile = { ...options }; Object.defineProperty(hostile, 'tcBinary', { enumerable: true, get() { invoked = true; return options.tcBinary; } });
  assert.equal((await observeNetworkHostFixture(deployment, hostile, f.reader)).verified, false);
  assert.equal(invoked, false);
});
